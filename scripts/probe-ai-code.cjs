const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
const base = process.env.LADLE_URL || 'http://localhost:61000';
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const page = await b.newPage({ viewport: { width: 1100, height: 900 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const go = async s => { await page.goto(`${base}/?story=${s}&mode=preview`); await page.locator('.ai-surface').first().waitFor(); };
  await go('ai-code--bloque');
  const block = page.locator('.ai-code').first();
  await block.getByRole('button', { name: 'Ejecutar' }).click();
  await block.locator('.ai-code-output pre').waitFor();
  assert.ok((await block.locator('.ai-code-output pre').innerText()).includes('36.3'));
  await block.getByRole('button', { name: 'Aplicar' }).click();
  await page.getByText('Aplicadas 15 líneas.').waitFor();
  await block.getByRole('button', { name: 'Explicar' }).click();
  assert.ok((await page.getByText('Petición al asistente', { exact: false }).innerText()).includes('Explica qué hace'));
  const failing = page.locator('.ai-code').nth(1);
  await failing.getByRole('button', { name: 'Ejecutar' }).click();
  await failing.locator('.ai-code-output[data-status=error]').waitFor();
  await go('ai-code--diff');
  const diff = page.locator('.ai-diff').first();
  assert.ok(await diff.locator('.ai-diff-line[data-type=add]').count() > 0);
  await diff.getByRole('button', { name: 'Aceptar cambios' }).click();
  await diff.getByText('Cambios aceptados').waitFor();
  const folded = page.locator('.ai-diff').nth(1);
  const before = await folded.locator('.ai-diff-line').count();
  await folded.locator('.ai-diff-skip').first().click();
  assert.ok(await folded.locator('.ai-diff-line').count() > before);
  await go('ai-code--seleccion');
  const ta = page.locator('.ai-code-artifact textarea');
  await ta.click(); await page.keyboard.press('Control+Home'); await page.keyboard.press('Shift+ArrowDown'); await page.keyboard.press('Shift+ArrowDown');
  await page.locator('.ai-selection-bar').waitFor();
  await page.locator('.ai-selection-bar').getByRole('button', { name: 'Explicar' }).click();
  assert.ok((await page.getByText('Petición al asistente', { exact: false }).innerText()).includes('export function total'));
  await go('ai-code--acciones-de-plugin');
  await page.getByRole('button', { name: 'Traducir comentarios' }).click();
  assert.ok((await page.getByText('Petición al asistente', { exact: false }).innerText()).includes('Traduce'));
  assert.deepEqual(errors, []);
  console.log('OK code block run/apply/ask, diff accept/expand, selection actions, plugin action');
  await b.close();
})().catch(e => { console.error(e); process.exit(1); });
