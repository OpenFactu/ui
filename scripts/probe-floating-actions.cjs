require('./test-support.cjs');
const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
const { THEME_PRESETS } = require('../src/theme/presets.ts');
const { resolveTheme, themeToCssVars } = require('../src/theme/tokens.ts');
const fs = require('node:fs');
const base = process.env.LADLE_URL || 'http://localhost:61000';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const goto = async story => { await page.goto(`${base}/?story=${story}&mode=preview`); await page.locator('.k-floating-actions-trigger').waitFor(); };
    await goto('floating-action-button--basico');
    const trigger = page.locator('.k-floating-actions-trigger');
    const menu = page.getByRole('menu', { name: 'Crear o actuar', exact: true });
    await trigger.click();
    const first = page.getByRole('menuitem', { name: 'Nueva factura', exact: true }); await first.click();
    await page.getByRole('status').filter({ hasText: 'Preparando una nueva factura' }).waitFor();
    assert.equal(await trigger.getAttribute('aria-expanded'), 'false');
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
    await trigger.press('ArrowDown'); await first.waitFor();
    assert.equal(await first.evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('End');
    assert.equal(await page.getByRole('menuitem', { name: 'Guardar cambios', exact: true }).evaluate(el => el === document.activeElement), true, 'disabled actions are skipped');
    await page.keyboard.press('Escape'); assert.equal(await trigger.getAttribute('aria-expanded'), 'false');
    await trigger.click(); await page.getByRole('button', { name: 'Limpiar resultado', exact: true }).click();
    assert.equal(await trigger.getAttribute('aria-expanded'), 'false', 'outside tap closes');
    await trigger.click(); await page.getByRole('menuitem', { name: 'Guardar cambios', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Cambios guardados' }).waitFor();
    assert.equal(await trigger.getAttribute('aria-expanded'), 'false');
    await page.evaluate(() => { const input = document.createElement('input'); input.setAttribute('aria-label', 'Otro campo'); document.querySelector('main').append(input); });
    await page.getByRole('button', { name: 'Limpiar resultado', exact: true }).click();
    await trigger.click(); await page.getByRole('menuitem', { name: 'Guardar cambios', exact: true }).click();
    const other = page.getByRole('textbox', { name: 'Otro campo', exact: true }); await other.click(); await other.fill('a');
    await page.getByRole('status').filter({ hasText: 'Cambios guardados' }).waitFor();
    assert.equal(await other.evaluate(el => el === document.activeElement), true, 'a completed action does not steal focus after outside dismissal');
    await page.getByRole('button', { name: 'Limpiar resultado', exact: true }).click();
    await trigger.click(); await page.getByRole('menuitem', { name: 'Guardar cambios', exact: true }).click();
    await other.click();
    assert.equal(await trigger.isVisible(), false, 'floating actions yield space during mobile text editing');
    await other.blur(); await trigger.click();
    await page.getByRole('status').filter({ hasText: 'Cambios guardados' }).waitFor();
    assert.equal(await trigger.getAttribute('aria-expanded'), 'true', 'an old action does not close a newer menu opening');
    await page.keyboard.press('Escape');
    await trigger.click();
    fs.mkdirSync('.shots/floating-actions', { recursive: true });
    for (const preset of THEME_PRESETS) {
      const theme = resolveTheme(preset.theme);
      await page.evaluate(vars => { for (const [key, value] of Object.entries(vars)) document.documentElement.style.setProperty(key, value); }, themeToCssVars(theme));
      assert.ok(await trigger.evaluate(el => { const box = el.getBoundingClientRect(); return box.width >= 48 && box.height >= 48 && box.bottom <= innerHeight && box.right <= innerWidth; }), preset.id);
      assert.ok(await menu.evaluate(el => { const box = el.getBoundingClientRect(); return box.top >= 0 && box.left >= 0 && box.right <= innerWidth; }), `${preset.id}: actions fit mobile`);
    }
    await page.locator('.k-floating-actions').screenshot({ path: '.shots/floating-actions/mobile.png' });
    assert.equal(await page.locator('.k-floating-actions-panel').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
    await page.setViewportSize({ width: 320, height: 380 });
    assert.ok(await trigger.evaluate(el => el.getBoundingClientRect().bottom <= innerHeight));
    await page.keyboard.press('Escape');
    await goto('floating-action-button--izquierda'); await page.locator('.k-floating-actions-trigger').click();
    assert.ok(await page.locator('.k-floating-actions').evaluate(el => el.getBoundingClientRect().left >= 0 && el.getBoundingClientRect().left < innerWidth / 2));
    await goto('floating-action-button--controlado'); await page.getByRole('button', { name: 'Abrir acciones', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Enviar mensaje', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Mensaje enviado' }).waitFor();
    assert.equal(await page.locator('.k-floating-actions-trigger').getAttribute('aria-expanded'), 'false');
    await goto('floating-action-button--con-error'); await page.locator('.k-floating-actions-trigger').click();
    await page.getByRole('menuitem', { name: 'Probar error', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Puedes volver a intentarlo' }).waitFor();
    assert.equal(await page.locator('.k-floating-actions-trigger').getAttribute('aria-expanded'), 'true');
    assert.deepEqual(errors, []);
    console.log(`OK floating actions: pointer/keyboard, async/error, controlled state, both positions, mobile and ${THEME_PRESETS.length} themes`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
