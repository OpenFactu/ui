const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
const base = process.env.LADLE_URL || 'http://localhost:61000';
(async () => {
  const meta = await (await fetch(`${base}/meta.json`)).json();
  assert.ok(meta.stories['code-editor--basico'], 'CodeEditor story is not implemented yet');
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1100, height: 850 } });
    page.on('pageerror', error => errors.push(error.message));
    const goto = async story => { await page.goto(`${base}/?story=code-editor--${story}&mode=preview`); await page.locator('.k-code-editor textarea').first().waitFor(); };
    await goto('basico');
    const editor = page.getByRole('textbox', { name: 'Código', exact: true });
    const value = () => editor.inputValue();
    const select = async (start, end = start) => editor.evaluate((el, selection) => { el.focus(); el.setSelectionRange(...selection); }, [start, end]);
    await editor.fill('');
    await editor.press('{');
    assert.equal(await value(), '{}');
    await editor.press('Enter');
    assert.equal(await value(), '{\n  \n}');
    await editor.press('Control+z');
    assert.equal(await value(), '{}');
    await editor.press('Control+Shift+z');
    assert.equal(await value(), '{\n  \n}');
    await editor.fill('one\ntwo');
    await select(0, 7);
    await editor.press('Tab');
    assert.equal(await value(), '  one\n  two');
    await editor.press('Shift+Tab');
    assert.equal(await value(), 'one\ntwo');
    await editor.fill('const count = 1;\ncou');
    await select((await value()).length);
    await editor.press('Control+Space');
    await page.getByRole('option', { name: 'count', exact: true }).waitFor();
    await editor.press('Enter');
    assert.equal(await value(), 'const count = 1;\ncount');
    await editor.fill('One one one');
    await editor.press('Control+f');
    await page.getByRole('textbox', { name: 'Buscar en el código' }).fill('one');
    await page.getByRole('textbox', { name: 'Reemplazar por' }).fill('two');
    await page.getByRole('button', { name: 'Reemplazar todo', exact: true }).click();
    assert.equal(await value(), 'two two two');
    await editor.press('Control+z');
    assert.equal(await value(), 'One one one');
    await page.getByRole('button', { name: 'Cerrar búsqueda' }).click();
    await editor.fill('<img src=x onerror="window.__injected=true">');
    assert.equal(await page.locator('.k-code-editor img').count(), 0);
    assert.equal(await page.evaluate(() => window.__injected), undefined);
    await editor.fill('const ' + 'longName'.repeat(200) + '\n' + 'const x = 1;\n'.repeat(100));
    assert.ok(await page.locator('.k-code-body').evaluate(el => el.clientHeight <= el.querySelector('textarea').offsetHeight + 1), 'gutter must not stretch viewport to document height');
    await select(35, 40);
    await editor.evaluate(el => { el.scrollTop = 120; el.scrollLeft = 80; el.dispatchEvent(new Event('scroll')); });
    const before = await editor.evaluate(el => ({ start: el.selectionStart, end: el.selectionEnd, top: el.scrollTop, left: el.scrollLeft }));
    await page.getByRole('combobox', { name: 'Tema del editor' }).click();
    await page.getByRole('option', { name: 'Oscuro', exact: true }).click();
    const after = await editor.evaluate(el => ({ start: el.selectionStart, end: el.selectionEnd, top: el.scrollTop, left: el.scrollLeft }));
    assert.deepEqual(after, before, 'theme switch preserves selection and scroll');
    assert.ok(await editor.evaluate(el => document.activeElement === el), 'theme restores editor focus');
    await editor.press('Escape');
    await editor.press('Tab');
    assert.ok(await editor.evaluate(el => document.activeElement !== el), 'Escape then Tab exits');
    console.log('OK editing, history, completion, search, safe rendering and theme preservation');

    await goto('temas');
    const shells = page.locator('.k-code-editor');
    const backgrounds = await shells.evaluateAll(els => els.map(el => getComputedStyle(el).backgroundColor));
    assert.ok(new Set(backgrounds).size >= 3, 'independent themes');
    const explicitBefore = backgrounds.slice(1);
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    const darkBackgrounds = await shells.evaluateAll(els => els.map(el => getComputedStyle(el).backgroundColor));
    assert.notEqual(darkBackgrounds[0], backgrounds[0], 'auto follows global theme');
    assert.deepEqual(darkBackgrounds.slice(1), explicitBefore, 'explicit editor themes stay local');
    console.log('OK independent themes and automatic global theme');

    await goto('personalizado');
    assert.ok(await page.locator('.k-code-highlight [data-token="keyword"]').count() > 0, 'custom language');
    const custom = page.getByRole('textbox', { name: 'Fórmula', exact: true });
    await custom.fill('SU');
    await custom.press('Control+End');
    await custom.press('Control+Space');
    await custom.press('Enter');
    assert.equal(await custom.inputValue(), 'SUMA()', 'custom insertText wins over keyword suggestion');
    await goto('estados');
    assert.ok(await page.getByRole('textbox', { name: 'Solo lectura' }).getAttribute('readonly') !== null);
    assert.ok(await page.getByRole('textbox', { name: 'Deshabilitado' }).isDisabled());
    const minimal = page.locator('.k-code-editor').filter({ has: page.getByRole('textbox', { name: 'Solo código', exact: true }) });
    assert.equal(await minimal.getByRole('combobox').count(), 0, 'minimal editor has no theme selector');
    assert.equal(await minimal.locator('.k-code-toolbar,.k-code-gutter,.k-code-status').count(), 0, 'minimal editor shows only code');
    const codeOnly = minimal.getByRole('textbox');
    await codeOnly.fill(''); await codeOnly.press('{');
    assert.equal(await codeOnly.inputValue(), '{}', 'minimal editor keeps editing commands');
    await codeOnly.fill('const clientes = [];\ncli');
    await codeOnly.press('Control+End'); await codeOnly.press('Control+Space');
    await minimal.getByRole('option', { name: 'clientes', exact: true }).waitFor();
    await codeOnly.press('Enter');
    assert.equal(await codeOnly.inputValue(), 'const clientes = [];\nclientes', 'minimal editor keeps autocomplete');
    await codeOnly.fill(''); await codeOnly.press('Control+Space');
    assert.ok(await minimal.evaluate(el => {
      const menu = el.querySelector('.k-code-completions').getBoundingClientRect();
      const viewport = el.querySelector('.k-code-viewport').getBoundingClientRect();
      const style = getComputedStyle(el.querySelector('textarea'));
      const caretBottom = viewport.top + parseFloat(style.paddingTop) + parseFloat(style.lineHeight);
      return menu.top >= caretBottom && menu.bottom <= viewport.bottom;
    }), 'completion menu fits inside a short minimal editor');
    await goto('documento-grande');
    assert.ok(await page.locator('.k-code-highlight').evaluate(el => el.querySelectorAll('*').length < 2000), 'large documents render a bounded number of highlight nodes');
    assert.equal((await page.locator('.k-code-editor textarea').inputValue()).split('\n').length, 3000);
    await page.locator('.k-code-editor textarea').press('Control+End');
    await page.locator('.k-code-editor textarea').press('Enter');
    assert.equal((await page.locator('.k-code-editor textarea').inputValue()).split('\n').length, 3001);
    assert.ok((await page.locator('.k-code-gutter').innerText()).includes('3001'), 'line numbers follow the viewport at the end');
    await page.setViewportSize({ width: 390, height: 800 });
    await goto('basico');
    await page.getByRole('textbox', { name: 'Código', exact: true }).fill('\tconst x = 1;');
    const metrics = await page.locator('.k-code-viewport').evaluate(el => {
      const text = getComputedStyle(el.querySelector('textarea'));
      const highlight = getComputedStyle(el.querySelector('pre'));
      return ['fontFamily', 'fontSize', 'lineHeight', 'letterSpacing', 'tabSize', 'paddingLeft'].map(key => [key, text[key], highlight[key]]);
    });
    for (const [key, text, highlight] of metrics) assert.equal(highlight, text, `highlight alignment: ${key}`);
    assert.ok(await page.locator('.k-code-editor').evaluate(el => el.getBoundingClientRect().right <= innerWidth), 'mobile layout fits');
    assert.deepEqual(errors, [], 'no browser errors');
    console.log('OK custom language, read-only/disabled states, 3000 lines and mobile');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
