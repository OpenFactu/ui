const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
const base = process.env.LADLE_URL || 'http://localhost:61000';
(async () => {
  const meta = await (await fetch(`${base}/meta.json`)).json();
  assert.ok(meta.stories['ai-workspace--completo'], 'AI workspace demo is not implemented yet');
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const goto = async story => { await page.goto(`${base}/?story=${story}&mode=preview`); await page.locator('.ai-surface').first().waitFor(); };
    const input = () => page.locator('.ai-composer textarea');
    await goto('ai-workspace--completo');
    await page.locator('.ai-workspace').waitFor();
    const frame = page.frameLocator('iframe.ai-html-preview');
    await frame.getByRole('button', { name: 'Añadir una idea' }).click();
    assert.equal(await frame.locator('#count').textContent(), '13');
    const separator = page.getByRole('separator', { name: 'Cambiar ancho de resultados' });
    await separator.focus(); await separator.press('ArrowLeft');
    assert.equal(await separator.getAttribute('aria-valuenow'), '42');
    await page.getByRole('combobox', { name: 'Versión' }).click();
    await page.getByRole('option', { name: 'Respuesta breve', exact: true }).click();
    assert.ok((await page.locator('.ai-message[data-role="assistant"]').innerText()).includes('Empieza con una idea concreta'));
    await page.getByRole('combobox', { name: 'Versión' }).click();
    await page.getByRole('option', { name: 'Respuesta detallada', exact: true }).click();
    await input().fill('Borrador conservado');
    await page.getByRole('button', { name: 'Notas e ideas', exact: true }).click();
    assert.equal(await input().inputValue(), '');
    await page.getByRole('button', { name: 'Un nuevo proyecto', exact: true }).click();
    assert.equal(await input().inputValue(), 'Borrador conservado');
    await page.getByRole('tab', { name: 'Resumen', exact: true }).click();
    await page.locator('.ai-artifact-toolbar').getByRole('button', { name: 'Código', exact: true }).click();
    await page.locator('.ai-document-editor').fill('# Documento editado');
    await page.locator('.ai-artifact-toolbar').getByRole('button', { name: 'Vista previa' }).click();
    await page.locator('.ai-artifact-body').getByRole('heading', { name: 'Documento editado' }).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.locator('.ai-artifact-toolbar').getByRole('button', { name: 'Descargar' }).click();
    assert.equal((await downloadPromise).suggestedFilename(), 'resumen.md');
    // The isolated HTML permits its own inline scripts but blocks parent access and network resources.
    await page.getByRole('tab', { name: 'Panel de ideas', exact: true }).click();
    await page.locator('.ai-artifact-toolbar').getByRole('button', { name: 'Código', exact: true }).click();
    const requested = []; page.on('request', request => { if (request.url().includes('example.invalid')) requested.push(request.url()); });
    await page.locator('.ai-artifact-body textarea').fill(`<p id="isolation">pending</p><img src="https://example.invalid/pixel"><script>try{parent.document.body.dataset.escaped='yes'}catch{document.getElementById('isolation').textContent='isolated'}fetch('https://example.invalid/api').catch(()=>document.body.dataset.blocked='yes')</script>`);
    await page.locator('.ai-artifact-toolbar').getByRole('button', { name: 'Vista previa' }).click();
    await frame.locator('#isolation').waitFor();
    assert.equal(await frame.locator('#isolation').textContent(), 'isolated');
    assert.equal(await page.locator('body').getAttribute('data-escaped'), null);
    await frame.locator('body[data-blocked="yes"]').waitFor();
    assert.equal(await page.locator('iframe.ai-html-preview').getAttribute('sandbox'), 'allow-scripts');
    // CSP-blocked requests can be reported by Playwright as failed, so inspect completion, not request notifications.
    assert.equal(await frame.locator('img').evaluate(image => image.naturalWidth), 0);
    console.log('OK versions, draft preservation, result editing/download, resizing and isolated HTML');

    await goto('ai-workspace--vacio');
    await input().fill('@Ven'); await input().press('End');
    await page.getByRole('option', { name: /@Ventas/ }).waitFor();
    await input().press('Enter'); assert.equal(await input().inputValue(), '@Ventas ');
    assert.equal(await page.locator('.ai-message').count(), 0, 'mention acceptance must not send');
    await input().fill('/res'); await input().press('End'); await input().press('Tab');
    assert.equal(await input().inputValue(), 'Resume la conversación ');
    await input().fill('Prueba de composición');
    await input().dispatchEvent('compositionstart');
    await input().press('Enter');
    assert.equal(await page.locator('.ai-message').count(), 0);
    await input().dispatchEvent('compositionend');
    await input().press('Shift+Enter');
    assert.ok((await input().inputValue()).includes('\n'));
    await page.locator('.ai-composer input[type="file"]').setInputFiles({ name: 'notas.txt', mimeType: 'text/plain', buffer: Buffer.from('Demo local') });
    await page.locator('.ai-attachment[data-status="ready"]').waitFor();
    await input().fill('Preparar propuesta'); await input().press('Enter');
    await page.getByRole('button', { name: 'Aprobar', exact: true }).waitFor();
    assert.equal(await page.locator('.ai-message[data-role="user"]').count(), 1);
    assert.equal(await input().inputValue(), '', 'demo host clears accepted drafts');
    await input().fill('Siguiente borrador');
    await page.getByRole('button', { name: 'Aprobar', exact: true }).click();
    await page.getByRole('button', { name: 'Detener respuesta' }).click();
    await page.locator('p[role="status"]').filter({ hasText: 'Respuesta detenida' }).waitFor();
    assert.equal(await input().inputValue(), 'Siguiente borrador');
    await input().fill('error'); await input().press('Enter');
    await page.getByRole('button', { name: 'Reintentar', exact: true }).click();
    await page.getByRole('button', { name: 'Aprobar', exact: true }).click();
    await page.getByRole('button', { name: /Resumen editable/ }).waitFor();
    assert.equal(await page.locator('.ai-message[data-role="user"]').count(), 2, 'retry must reuse failed turn');
    await page.getByRole('button', { name: /Resumen editable/ }).click();
    await page.getByRole('tab', { name: 'Resumen', exact: true }).waitFor();
    await page.locator('.ai-message[data-role="assistant"]').last().getByRole('button', { name: 'Respuesta útil' }).click();
    assert.equal(await page.locator('.ai-message[data-role="assistant"]').last().getByRole('button', { name: 'Respuesta útil' }).getAttribute('aria-pressed'), 'true');
    console.log('OK mentions, commands, IME, files, send, stop, retry, tool approval, result and feedback');

    await goto('ai-components--compositor');
    await input().fill('Borrador que debe permanecer');
    await input().press('Enter'); assert.equal(await input().inputValue(), 'Borrador que debe permanecer');
    await page.locator('.ai-composer input[type="file"]').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from([137,80,78,71]) });
    await page.getByRole('combobox', { name: 'Modelo' }).click();
    await page.getByRole('option', { name: 'Solo texto', exact: true }).click();
    assert.ok(await page.getByRole('button', { name: 'Enviar mensaje' }).isDisabled());
    await page.getByText('El modelo seleccionado no admite estos adjuntos.').waitFor();
    await page.getByRole('button', { name: /Quitar archivo/ }).click();
    assert.ok(await page.getByRole('button', { name: 'Enviar mensaje' }).isEnabled());
    await page.getByRole('combobox', { name: 'Modelo' }).click(); await page.getByRole('option', { name: 'Asistente general', exact: true }).click();
    await page.locator('.ai-composer input[type="file"]').setInputFiles({ name: 'large.txt', mimeType: 'text/plain', buffer: Buffer.alloc(1100000) });
    await page.getByText('Algunos archivos no cumplen los límites permitidos.').waitFor();
    await goto('ai-components--markdown');
    assert.equal(await page.locator('.ai-markdown img').count(), 0);
    assert.equal(await page.evaluate(() => window.__aiInjected), undefined);
    assert.equal(await page.locator('.ai-markdown a[href^="javascript:"]').count(), 0);
    assert.ok(await page.locator('.ai-markdown table').count());

    await goto('ai-workspace--conversacion-larga');
    await page.locator('.ai-message').nth(199).waitFor();
    assert.ok(await page.locator('.ai-code [data-token]').count() > 0);
    assert.ok(await page.locator('.ai-code [data-token]').count() < 300, 'long code is initially bounded');
    const scroll = page.locator('.ai-conversation-scroll');
    await scroll.evaluate(el => { el.scrollTop = el.scrollHeight / 2; });
    await page.waitForTimeout(100);
    const top = await scroll.evaluate(el => el.scrollTop);
    await page.getByRole('button', { name: 'Añadir mensaje simulado' }).click();
    assert.equal(await scroll.evaluate(el => el.scrollTop), top, 'new responses preserve previous reading position');
    await page.getByRole('button', { name: 'Ir a los mensajes nuevos' }).click();
    assert.ok(await scroll.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop < 5));
    await scroll.evaluate(el => { el.scrollTop = 0; });
    const anchor = page.locator('[data-message-id="message-0"]');
    // Relativo al contenedor de scroll: el desplazamiento de la ventana (la story es más alta que el viewport) no es la métrica.
    const anchorTop = () => anchor.evaluate(el => el.getBoundingClientRect().top - el.closest('.ai-conversation-scroll').getBoundingClientRect().top);
    const anchorBefore = await anchorTop();
    await page.getByRole('button', { name: 'Cargar mensajes anteriores' }).click();
    assert.ok(Math.abs((await anchorTop()) - anchorBefore) < 3, 'prepending preserves visual anchor');
    await page.getByRole('button', { name: 'Ver código completo' }).click();
    assert.ok(await page.locator('.k-code-highlight [data-token]').count() < 1000, 'expanded long code remains virtualized');
    console.log('OK controlled drafts, model capabilities, Markdown safety, 200-message anchoring and 3,000-line code');

    await page.setViewportSize({ width: 390, height: 844 });
    await goto('ai-workspace--completo');
    await page.getByRole('tab', { name: 'Conversación', exact: true }).click();
    await input().fill('Borrador móvil');
    await page.getByRole('tab', { name: 'Resultados', exact: true }).click();
    await page.getByRole('tab', { name: 'Conversación', exact: true }).click();
    assert.equal(await input().inputValue(), 'Borrador móvil');
    await page.getByRole('button', { name: 'Abrir historial' }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Notas e ideas', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'mobile workspace fits viewport');
    await page.screenshot({ path: '.shots/ai-mobile.png' });
    assert.deepEqual(errors, []);
    console.log('OK mobile panels, history and preserved draft; no browser exceptions');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
